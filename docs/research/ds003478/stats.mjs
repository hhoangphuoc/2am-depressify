// One-off stats over OpenNeuro ds003478 participants.tsv (CC0).
// Usage: node docs/research/ds003478/stats.mjs  → prints and writes findings.md next to this file.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const text = readFileSync(join(here, "data", "participants.tsv"), "utf8").trim();
const [header, ...lines] = text.split(/\r?\n/);
const cols = header.split("\t");
const rows = lines.map((l) => Object.fromEntries(l.split("\t").map((v, i) => [cols[i], v])));

const num = (v) => {
  const n = Number(v);
  return v === undefined || v === "" || v === "n/a" || Number.isNaN(n) ? null : n;
};

function pearson(pairs) {
  const n = pairs.length;
  const mx = pairs.reduce((s, [x]) => s + x, 0) / n;
  const my = pairs.reduce((s, [, y]) => s + y, 0) / n;
  let sxy = 0, sxx = 0, syy = 0;
  for (const [x, y] of pairs) {
    sxy += (x - mx) * (y - my);
    sxx += (x - mx) ** 2;
    syy += (y - my) ** 2;
  }
  return { n, r: sxy / Math.sqrt(sxx * syy) };
}

const range = (xs) => `${Math.min(...xs)}–${Math.max(...xs)}`;

// sub-544 (Original_ID) was excluded by the authors: unstable BDI between screen and lab.
const used = rows.filter((r) => r.Original_ID !== "544");

const bdiStai = pearson(
  used.map((r) => [num(r.BDI), num(r.STAI)]).filter(([a, b]) => a !== null && b !== null),
);
const interviewed = used.filter((r) => r.SCID !== "No Interview");
const bdiHamd = pearson(
  interviewed.map((r) => [num(r.BDI), num(r.HamD)]).filter(([a, b]) => a !== null && b !== null),
);

const scidCounts = {};
for (const r of rows) scidCounts[r.SCID] = (scidCounts[r.SCID] ?? 0) + 1;

const bdiAll = used.map((r) => num(r.BDI)).filter((x) => x !== null);
const bdiInterviewed = interviewed.map((r) => num(r.BDI)).filter((x) => x !== null);
const hamd = interviewed.map((r) => num(r.HamD)).filter((x) => x !== null);
const fmt = (x) => x.toFixed(2);

const out = `# ds003478 findings (generated by stats.mjs, do not edit by hand)

Source: OpenNeuro ds003478 v1.1.0, participants.tsv (CC0). Rows: ${rows.length}; analysed: ${used.length} (sub with Original_ID 544 excluded, as by the authors).

| Measure | Value |
|---|---|
| BDI–STAI correlation (all with both scores) | r = ${fmt(bdiStai.r)}, n = ${bdiStai.n} |
| BDI–HAM-D correlation (SCID-interviewed only) | r = ${fmt(bdiHamd.r)}, n = ${bdiHamd.n} |
| BDI range, whole sample | ${range(bdiAll)} |
| BDI range, interviewed | ${range(bdiInterviewed)} |
| HAM-D range, interviewed | ${range(hamd)} |

SCID groups (all ${rows.length} rows):
${Object.entries(scidCounts).map(([k, v]) => `- ${k}: ${v}`).join("\n")}

## Caveats
- Interviewed participants were drawn from the high-BDI group only, so the BDI–HAM-D correlation is computed on a range-restricted sample; it understates agreement across the full severity range.
- College students, single visit, circa 2008–2010; no TMS, treatment or follow-up. Not representative of post-TMS patients.
`;

writeFileSync(join(here, "findings.md"), out);
console.log(out);
