import assert from 'node:assert/strict';
import { attentionFor, baseline, clearFlags, createPatients, effectivePatients, makeDigest, orderPatients, raiseFlag, timelinePhases, validateVisit, withdrawSharing } from './data.mjs';

const patients = createPatients();
const reversed = [...patients].reverse();
const before = reversed.map(p => p.id);
assert.deepEqual(orderPatients(reversed).map(p => p.level), ['red', 'amber', 'green', 'green']);
assert.deepEqual(reversed.map(p => p.id), before, 'Sorting must not mutate the original data');
assert.equal(validateVisit({ date: '2026-11-13', type: 'PHQ-2', score: '6' }), '');
for (const score of ['7', '-1', '2.5', '', ' ', null, 'abc']) assert.ok(validateVisit({ date: '2026-11-13', type: 'PHQ-2', score }));
assert.equal(validateVisit({ date: '2026-11-13', type: 'PHQ-9', score: '27' }), '');
assert.ok(validateVisit({ date: '2026-11-13', type: 'PHQ-9', score: '28' }));
assert.ok(validateVisit({ date: '2026-11-14', type: 'none', score: '' }));
assert.ok(validateVisit({ date: '2026-02-30', type: 'none', score: '' }));
assert.equal(validateVisit({ date: '2026-11-13', type: 'none', score: '' }), '');
const days = Array.from({ length: 14 }, (_, i) => ({ date: `2026-11-${String(i + 1).padStart(2, '0')}`, sleep: i < 4 ? 0 : null }));
assert.equal(baseline(days, 'sleep').value, null, 'Fewer than five valid days cannot form a Baseline');
days[4].sleep = 5;
assert.equal(baseline(days, 'sleep').value, 0, 'True zero is valid; null and future dates are excluded');
assert.equal(baseline([], 'sleep').value, null);
assert.equal(baseline([1,2,3,4,5,100].map((sleep,i)=>({date:`2026-11-${String(i+1).padStart(2,'0')}`,sleep})), 'sleep').value,3.5,'Baseline is median, including even sample counts');
assert.equal(makeDigest([]), null);
assert.equal(makeDigest(patients[0].summaries).ids.length, 4);
assert.match(effectivePatients(patients, 'silence')[0].reason, /Phone quiet/);
const silent = effectivePatients(patients, 'silence')[0];
assert.equal(silent.daily.at(-1).sleep, null, 'A quiet phone must not report new Signals');
assert.equal(silent.history[0].id, 'silence', 'The raised reason must be available to preserve when cleared');
const amber = { id: 'new-amber', level: 'amber', reason: 'Steps fell over several days.', source: 'Steps aggregate', observed: '13 Nov, 14:20' };
const retained = raiseFlag(patients[0], amber);
assert.equal(retained.level, 'red', 'A new amber reason cannot downgrade an uncleared red');
assert.equal(retained.activeFlags.length, 2);
assert.equal(attentionFor({ ...retained, assessmentStatus: 'unavailable' }).level, 'red');
assert.equal(attentionFor({ ...patients[2], assessmentStatus: 'unavailable' }).level, 'unknown', 'Timeout is not an automatically green result');
const cleared = clearFlags(retained, 'Spoke with Patient.');
assert.equal(cleared.activeFlags.length, 0);
assert.equal(cleared.history.filter(h => h.action === 'Cleared').length, 3, 'Both new reasons and the older cleared reason stay in history');
const withdrawn = withdrawSharing(retained);
assert.equal(withdrawn.alertsEnabled, false);
assert.deepEqual([withdrawn.daily, withdrawn.summaries, withdrawn.activeFlags, withdrawn.history], [[], [], [], []]);
assert.deepEqual(raiseFlag(withdrawn, amber), withdrawn, 'No new alerts after sharing is withdrawn');
assert.equal(effectivePatients([withdrawn], 'silence')[0].level, 'hidden', 'Changing view cannot reveal deleted flags');
assert.deepEqual(timelinePhases(null, patients[0].visits), []);
assert.deepEqual(timelinePhases('2026-10-02', [...patients[0].visits, { date: '2026-11-05' }, { date: '2026-10-15' }]).map(p => [p.start, p.end]), [['2026-10-02', '2026-10-15'], ['2026-10-15', '2026-10-23'], ['2026-10-23', '2026-11-05'], ['2026-11-05', '2026-11-13']], 'Backdated Visits split Phases at their actual date');
assert.ok(patients.find(p => p.id === 'alex').daily.every(row => row.hrv === null), 'Missing device HRV is never replaced with seeded HRV');
for (const patient of patients) {
  assert.equal(patient.daily.length, 43);
  for (const summary of patient.summaries) assert.equal(patient.daily.find(d => d.date === summary.date).mood, summary.mood, 'Charts and Summaries must agree');
}
console.log('Clinician data self-check passed: flag priority/history, timeout, Consent deletion, PHQ ranges, gaps, device HRV, Baseline and backdated Phases.');
